#!/usr/bin/perl
#
# Mechanical pass of custom-pr-reviewer: reports candidate "tiny weirdness" in the
# lines a diff ADDS. Every hit is a candidate for the reviewer to judge, not a
# verdict. Reads `git diff -U0` on stdin; $ARGV[0] is the post-image revision
# ("WORKTREE" reads the files from disk).

use strict;
use warnings;

my $revision = shift // 'HEAD';

my (%added_lines, %hunks, @order);
my ($file, $hunk);

while (my $line = <STDIN>) {
	if ($line =~ m{^\+\+\+ (?:b/(.*)|/dev/null)$}) {
		$file = $1;

		push @order, $file if defined $file;

		next;
	}

	next unless defined $file;

	if ($line =~ /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/) {
		$hunk = {added => [], removed => [], start => $1};

		push @{$hunks{$file}}, $hunk;

		next;
	}

	next unless $hunk;

	chomp $line;

	if ($line =~ /^\+(.*)$/) {
		my $number = $hunk->{start} + scalar @{$hunk->{added}};

		push @{$hunk->{added}}, [$number, $1];

		$added_lines{$file}{$number} = 1;
	}
	elsif ($line =~ /^-(.*)$/) {
		push @{$hunk->{removed}}, $1;
	}
}

sub _content {
	my ($path) = @_;

	local $/;

	my $content;

	if ($revision eq 'WORKTREE') {
		open my $fh, '<', $path or return '';

		$content = <$fh>;
	}
	else {
		open my $fh, '-|', 'git', 'show', "$revision:$path" or return '';

		$content = <$fh>;
	}

	return $content // '';
}

sub _is_generated {
	my ($content) = @_;

	return $content =~ /\@generated|\@Generated\(""\)|\$ANTLR|# This is a generated file\.|## Autogenerated|Code generated .* DO NOT EDIT/;
}

sub _line_of {
	my ($content, $offset) = @_;

	return 1 + (substr($content, 0, $offset) =~ tr/\n//);
}

sub _report {
	my ($check, $path, $number, $text) = @_;

	$text =~ s/\s+/ /g;
	$text =~ s/^ | $//g;

	printf "%s\t%s:%d\t%s\n", $check, $path, $number, substr($text, 0, 160);
}

my $language_key_pattern = qr{(?:_language\.get|LanguageUtil\.get|Liferay\.Language\.get)\([^'"]*['"]([a-z0-9.-]+)['"]|<liferay-ui:message key="([a-z0-9.-]+)"};

my $feature_flag_pattern = qr{FeatureFlagManagerUtil\.isEnabled|Liferay\.FeatureFlags\[|featureFlag|FeatureFlags\.};

my $diff_adds_feature_flag = 0;

for my $path (@order) {
	next if $path =~ m{/test/|/testIntegration/|\.test\.[jt]sx?$};

	for my $hunk (@{$hunks{$path} // []}) {
		$diff_adds_feature_flag = 1 if grep { $_->[1] =~ $feature_flag_pattern } @{$hunk->{added}};
	}
}

for my $path (@order) {
	next unless $added_lines{$path};

	my $content = _content($path);

	next if _is_generated($content);

	my $is_test = $path =~ m{/test/|/testIntegration/|\.test\.[jt]sx?$};

	if ($path =~ /\.java$/) {

		# A membership test against a 2-3 element inline array literal: an
		# over engineered form of a == chain.

		while ($content =~ /ArrayUtil\.contains\(\s*new\s+\w+\[\]\s*\{([^{}]*)\}/g) {
			my $literal = $1;
			my $number = _line_of($content, $-[0]);

			my $elements = 1 + (() = $literal =~ /,/g);

			next unless $elements <= 3;
			next unless $added_lines{$path}{$number};

			_report('JAVA_INLINE_ARRAY_MEMBERSHIP', $path, $number, "ArrayUtil.contains(new ...[] {$literal}, ...) with $elements elements");
		}

		# The same shape built through a collection factory.

		while ($content =~ /(?:Arrays\.asList|List\.of|Set\.of|SetUtil\.fromArray|ListUtil\.fromArray)\(([^()]*)\)\s*\.contains\(/g) {
			my $arguments = $1;
			my ($start, $end) = ($-[0], $+[0]);

			my $number = _line_of($content, $start);

			my $elements = 1 + (() = $arguments =~ /,/g);

			next unless $elements <= 3;
			next unless $added_lines{$path}{$number};

			_report('JAVA_INLINE_ARRAY_MEMBERSHIP', $path, $number, substr($content, $start, $end - $start));
		}

		# A call on the value that another call returns, on one line
		# (foo.getBar().getBaz()) or in the formatter's multi-line layout
		# (`).getJSONArray(` on its own line). Tests included. The check
		# applies also to JSONObject and JSONArray results, which Rule 402 lists
		# as fluent. Statements that assemble a
		# builder, a stream, a Mockito stub, or a JSON object are skipped.

		my %reported_statements;

		while ($content =~ /\)\s*\.\s*[A-Za-z_]\w*\s*\(/g) {
			my ($start, $end) = ($-[0], $+[0]);

			my $number = _line_of($content, $end);

			next unless $added_lines{$path}{$number};

			my $statement_start = 0;

			for my $delimiter (';', '{', '}') {
				my $index = rindex($content, $delimiter, $start);

				$statement_start = $index + 1 if $index + 1 > $statement_start;
			}

			next if $reported_statements{$statement_start}++;

			my $statement_end = index($content, ';', $end);

			$statement_end = length $content if $statement_end < 0;

			my $statement = substr($content, $statement_start, $statement_end - $statement_start);

			next if $statement =~ /Builder\b|[bB]uilder\(\)|\.build\(\)|\.stream\(\)|\bStream\.|\bOptional\b|StringBundler|JSONUtil\.|\.put\(|\bMockito\.|\.then(?:Answer|Return|Throw)\(|\.verify\(|\bdo(?:Answer|Nothing|Return|Throw)\(|\b(?:Duration|Instant|LocalDate|LocalDateTime)\b/;

			_report('JAVA_CHAINED_CALL', $path, $number, $statement);
		}

		# Calls on one receiver that are not sorted by method name, also when
		# other statements stand between them, such as a
		# ThemeDisplay setup between two calls on a request. Only top level statements of a method body and
		# set*, add* and put* calls are compared.

		my %calls;
		my $number = 0;

		for my $text (split /\n/, $content) {
			$number++;

			if ($text =~ /^\t(?:\S|\}$)/) {
				%calls = ();

				next;
			}

			next unless $text =~ /^\t\t([a-zA-Z_]\w*)\.((?:add|put|set)\w*)\(/;

			my ($receiver, $method) = ($1, $2);

			for my $call (@{$calls{$receiver} // []}) {
				my ($earlier_method, $earlier_number) = @$call;

				next unless lc($method) lt lc($earlier_method);
				next unless $added_lines{$path}{$number} || $added_lines{$path}{$earlier_number};

				_report('JAVA_RECEIVER_CALLS_UNSORTED', $path, $earlier_number, "$receiver.$earlier_method (line $earlier_number) comes before $receiver.$method (line $number)");

				last;
			}

			push @{$calls{$receiver}}, [$method, $number];
		}
	}

	if ($path =~ /\.tsx?$/ && !$is_test) {
		for my $hunk (@{$hunks{$path}}) {
			for my $added (@{$hunk->{added}}) {
				my ($number, $text) = @$added;

				next if $text =~ /^\s*import\b/;

				if ($text =~ /\bas\s+(?!const\b)([A-Za-z_][\w.<>\[\]]*)/) {
					_report('TS_TYPE_ASSERTION', $path, $number, $text);
				}
			}
		}

		while ($content =~ /\.\.\.\((?:[^;{}()]|\([^()]*\))*?(?:\?\s*\[\s*\]|:\s*\[\s*\]\s*\))/gs) {
			my $number = _line_of($content, $-[0]);

			next unless $added_lines{$path}{$number};

			_report('TS_CONDITIONAL_SPREAD', $path, $number, '...(condition ? [] : [...]) builds a list by spreading a conditional array');
		}
	}

	next if $is_test || !$diff_adds_feature_flag;

	# A user visible label replaced by another one in a hunk that does not
	# itself consult the feature flag, while the branch gates other parts of the
	# same feature. Verify the new label is meant for flag-off users too.

	for my $hunk (@{$hunks{$path}}) {
		my $added_text = join "\n", map { $_->[1] } @{$hunk->{added}};
		my $removed_text = join "\n", @{$hunk->{removed}};

		next if $added_text =~ $feature_flag_pattern;

		my %removed_keys;

		while ($removed_text =~ /$language_key_pattern/g) {
			$removed_keys{$1 // $2} = 1;
		}

		next unless %removed_keys;

		while ($added_text =~ /$language_key_pattern/g) {
			my $key = $1 // $2;

			next if $removed_keys{$key};

			my $number = $hunk->{added}[_line_of($added_text, $-[0]) - 1][0];

			_report('UNGATED_LABEL_CHANGE', $path, $number, "label now \"$key\" (was \"" . join('", "', sort keys %removed_keys) . "\") outside the feature flag gate");
		}
	}
}
